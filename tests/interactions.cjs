'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
assert.match(html,/<html lang="en">/);
for(const id of ['work','about','resume','contact'])assert.ok(html.includes('id="'+id+'"'),id);
for(const preview of ['swift-wakala-preview/','Fahari.io-preview/','tour-de-dar-preview/'])assert.ok(html.includes(preview),preview);
assert.ok((html.match(/href="Raymond_Duma_CV\.pdf"/g)||[]).length>=3,'CV accessibility');
assert.match(html,/<p>Raymonddjeff0502@gmail\.com<\/p>/);
assert.match(html,/<p>\+255 710 964 117<\/p>/);
assert.doesNotMatch(html,/mailto:|tel:|<form\b|<script\b/);
assert.match(css,/color-scheme:light/);assert.match(css,/@media\(max-width:460px\)/);assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length,'CSS brackets');
assert.ok(fs.existsSync(path.join(root,'Raymond_Duma_CV.pdf')),'CV PDF file');
assert.ok(fs.statSync(path.join(root,'Raymond_Duma_CV.pdf')).size>1000,'CV PDF nonempty');
console.log('PASS — project links, CV, plain contacts, responsive print layout.');
