"use strict";
const fs = require("node:fs");
const assert = require("node:assert/strict");
const html = fs.readFileSync(require("node:path").join(__dirname, "..", "index.html"), "utf8");
const css = fs.readFileSync(require("node:path").join(__dirname, "..", "styles.css"), "utf8");
assert.match(html, /<html lang="en">/);
assert.match(html, /id="work"/);
assert.match(html, /id="about"/);
assert.match(html, /id="contact"/);
assert.match(html, /Raymonddjeff0502@gmail\.com/);
assert.match(html, /\+255 710 964 117/);
assert.doesNotMatch(html, /mailto:|tel:/);
assert.ok((html.match(/href="Raymond_Duma_CV\.pdf"/g)||[]).length >= 3, "résumé download prominent");
for (const name of ["swift-wakala-preview/", "Fahari.io-preview/", "tour-de-dar-preview/"]) assert.ok(html.includes(name), name);
assert.doesNotMatch(html, /<canvas|command-dialog|terminal-form|script\.js/);
assert.match(css, /color-scheme:light/);
assert.match(css, /@media\(max-width:500px\)/);
console.log("Portfolio checks passed: light layout, links, résumé, plain contacts and mobile styles.");
