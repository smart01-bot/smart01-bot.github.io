"use strict";
const fs = require("node:fs");
const assert = require("node:assert/strict");
const path = require("node:path");
const root = path.join(__dirname,"..");
const html = fs.readFileSync(path.join(root,"index.html"),"utf8");
const css = fs.readFileSync(path.join(root,"styles.css"),"utf8");
assert.match(html, /<html lang="en">/);
for (const anchor of ["work","about","resume","contact"]) assert.ok(html.includes('id="'+anchor+'"'),anchor);
for (const target of ["swift-wakala-preview/","Fahari.io-preview/","tour-de-dar-preview/"]) assert.ok(html.includes(target),target);
assert.ok((html.match(/href="Raymond_Duma_CV\.pdf"/g)||[]).length >= 3,"résumé visible across the page");
assert.match(html,/Raymonddjeff0502@gmail\.com/);
assert.match(html,/\+255 710 964 117/);
assert.doesNotMatch(html, /mailto:|tel:|<script\b/,"no contact links, scripts or tracking");
assert.match(html,/<div class="contact-lines"/);
assert.match(css,/color-scheme:light/);
assert.match(css,/@media\(max-width:760px\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.ok(!html.includes("visual-mark"),"no oversized monogram art");
assert.ok(!html.includes("admin/overview"),"no private preview routes");
const localPdf = path.join(root,"Raymond_Duma_CV.pdf");
assert.ok(fs.existsSync(localPdf),"résumé PDF exists");
assert.ok(fs.statSync(localPdf).size > 1000,"résumé PDF is nonempty");
console.log("Portfolio checks passed: light layout, 3 previews, plain contacts, PDF, responsive styles.");
