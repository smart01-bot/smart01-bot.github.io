'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'styles.css'),'utf8');
assert.match(html,/<html lang="en">/);
for(const name of ['work','about','resume','contact'])assert.ok(html.includes('id="'+name+'"'),name);
for(const link of ['swift-wakala-preview/','Fahari.io-preview/','tour-de-dar-preview/'])assert.ok(html.includes(link),link);
assert.ok((html.match(/href="Raymond_Duma_CV\.pdf"/g)||[]).length>=3);
assert.match(html,/<p>Raymonddjeff0502@gmail\.com<\/p>/);
assert.match(html,/<p>\+255 710 964 117<\/p>/);
assert.doesNotMatch(html,/mailto:|tel:|<form\b|<script\b/);
assert.match(css,/color-scheme:light/);
assert.match(css,/@media\(max-width:620px\)/);
assert.match(css,/@media\(prefers-reduced-motion:reduce\)/);
assert.equal((css.match(/\{/g)||[]).length,(css.match(/\}/g)||[]).length);
console.log('PASS — links, résumé, contact text, light layout, mobile and reduced motion');
